# 파이썬의 자료구조 - 리스트, 딕셔너리, 튜플, 집합
# 집합(set) - 중복 불허, 순서가 없다. 중괄화 {} 사용
s1= {1, 2,3, 4}
print(s1) #{1, 2, 3, 4}

s2 = {'h', 'e', 'l', 'l', 'o'}
print(s2) #{'l', 'h', 'e', 'o'} 중복은 안되는데 순서가 없다

# 인덱싱 불가
# print(s2[0])

# 리스트
a1 = [1, 2, 3, 4, 4]
print(a1) #[1, 2, 3, 4, 4]

a2 = ['h', 'e', 'l', 'l', 'o']
print(a2) #['h', 'e', 'l', 'l', 'o']
print(a2[0]) #h